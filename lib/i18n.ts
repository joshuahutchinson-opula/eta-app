// Spanish copy keeps that voice rather than flattening it: signature
// phrases stay in patois where they work as brand words (like "Wah Gwan"),
// and phrases whose meaning depends on the patois wordplay are rewritten
// in natural Caribbean-flavoured Spanish instead of translated literally.
// Every such call is listed in PATOIS_TRANSLATION_NOTES for review by a
// native speaker.

