export type DictKey = BaseKey | keyof typeof more

const column = (i: 0 | 1 | 2 | 3) => Object.fromEntries(Object.entries(more).map(([k, v]) => [k, v[i]])) as Record<keyof typeof more, string>

const DICTS: Record<Lang, Record<DictKey, string>> = {
  en: { ...en, ...column(0) },
  es: { ...es, ...column(1) },
  de: { ...de, ...column(2) },
  fr: { ...fr, ...column(3) }
}

export function t(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  const text = DICTS[lang]?.[key] ?? DICTS.en[key] ?? key
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : text
}

export function normalizeLang(value: string | undefined | null): Lang {
  return value === 'es' || value === 'de' || value === 'fr' ? value : 'en'
}

